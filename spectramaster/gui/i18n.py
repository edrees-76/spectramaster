_lang = DEFAULT_LANGUAGE


def set_language(lang: str) -> str:
    """Activate a language ("ar"/"en"); unknown codes fall back to the default."""
    global _lang
    _lang = lang if lang in STRINGS else DEFAULT_LANGUAGE
    return _lang


def language() -> str:
    return _lang


def is_rtl(lang: str | None = None) -> bool:
    return (lang or _lang) == "ar"


def tr_in(lang: str | None, key: str, **kwargs) -> str:
    """Like ``tr`` but in an explicit language (thread-safe: no module state is changed)."""
    text = STRINGS.get(lang or _lang, {}).get(key)
    if text is None:
        text = STRINGS["en"].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def tr(key: str, **kwargs) -> str:
    text = STRINGS.get(_lang, {}).get(key)
    if text is None:
        text = STRINGS["en"].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def category_label(cat: str, lang: str | None = None) -> str:
    """Translated library category; compound ones ("fission/calibration") translate each part."""
    parts = [c.strip().lower() for c in (cat or "").split("/") if c.strip()]
    if not parts:
        return cat or ""
    out = []
    for c in parts:
        key = f"cat_{c}"
        text = tr_in(lang, key)
        out.append(c if text == key else text)
    return " / ".join(out)


LRI, PDI, LRM = "⁦", "⁩", "‎"


def ltr(text) -> str:
    """Left-to-right isolate (LRI ... PDI): numbers with units/signs, file names
    and paths keep their order inside right-to-left (Arabic) text."""
    text = "" if text is None else str(text)
    return f"{LRI}{text}{PDI}" if text else text


def bidi_path(path) -> str:
    """Display form of a file path / file name for any UI direction.

    The whole path is an LTR isolate and an LRM follows every separator, so
    Arabic folder names keep their left-to-right order (``D:\أ\ب`` would
    otherwise show as ``D:\ب\أ``) and ``.S0`` stays attached to its name.
    Display only -- strip with :func:`strip_bidi` before using it as a path."""
    text = "" if path is None else str(path)
    if not text:
        return text
    return ltr(text.replace("\\", "\\" + LRM).replace("/", "/" + LRM))


def strip_bidi(text: str) -> str:
    """Remove the invisible direction marks added by :func:`ltr` / :func:`bidi_path`."""
    return "".join(ch for ch in (text or "") if ch not in (LRI, PDI, LRM))


